CREATE TABLE review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id BIGINT NOT NULL REFERENCES consumer(id),
    product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(5000) NOT NULL CHECK (length(trim(comment)) > 0),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_review_consumer_product UNIQUE (consumer_id, product_id)
);

CREATE INDEX idx_review_product_created_at ON review(product_id, created_at DESC, id DESC);
