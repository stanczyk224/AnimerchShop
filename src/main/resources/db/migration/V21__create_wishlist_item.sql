CREATE TABLE wishlist_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_wishlist_item_consumer
        FOREIGN KEY (consumer_id) REFERENCES consumer(id) ON DELETE CASCADE,
    CONSTRAINT fk_wishlist_item_product
        FOREIGN KEY (product_id) REFERENCES product(id) ON DELETE CASCADE,
    CONSTRAINT uq_wishlist_consumer_product UNIQUE (consumer_id, product_id)
);

CREATE INDEX idx_wishlist_item_consumer_created_at
    ON wishlist_item (consumer_id, created_at DESC, id DESC);

CREATE INDEX idx_wishlist_item_product ON wishlist_item (product_id);
