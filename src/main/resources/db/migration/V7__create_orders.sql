CREATE TABLE customer_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    total_price NUMERIC(38, 2) NOT NULL,

    CONSTRAINT fk_customer_order_consumer
        FOREIGN KEY (consumer_id)
        REFERENCES consumer(id),

    CONSTRAINT chk_customer_order_total_price
        CHECK (total_price >= 0)
);

CREATE TABLE order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    quantity BIGINT NOT NULL,
    unit_price NUMERIC(38, 2) NOT NULL,

    CONSTRAINT fk_order_item_order
        FOREIGN KEY (consumer_order_id)
        REFERENCES customer_order(id),

    CONSTRAINT fk_order_item_product
        FOREIGN KEY (product_id)
        REFERENCES product(id),

    CONSTRAINT chk_order_item_quantity
        CHECK (quantity >= 1),

    CONSTRAINT chk_order_item_unit_price
        CHECK (unit_price >= 1000.00)
);
